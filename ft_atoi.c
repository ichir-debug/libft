#include "libft.h"

int	ft_atoi(const char *nptr)
{
	long	n;
	int		sign;
	int		i;

	i = 0;
	while (nptr[i] == 32 || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	sign = 1;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	n = 0;
	while ((nptr[i] >= '0' && nptr[i] <= '9') && n != 9223372036854775807)
	{
		if (n <= (9223372036854775807 - (nptr[i] - '0')) / 10)
			n = n * 10 + nptr[i] - '0';
		else
			n = 9223372036854775807;
		i++;
	}
	return ((int)(n * sign));
}
